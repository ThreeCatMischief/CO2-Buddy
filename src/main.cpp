void displayState(CURRENT_STATE state) {
  if(millis() - last_face_update >= face_duration) { // Time to update face
    if(awake_until - millis() < 1000) { // Less than 1 second left, extend awake time
      awake_until = millis() + 750;
    }
    switch(state) {
      case(PREHEAT):
        memcpy_P(current_face, fire[frame % 3], sizeof(current_face));
        frame++;
        break;
      case(GOOD):
        memcpy_P(current_face, face_good[rand() % 4], sizeof(current_face));
        break;
      case(OKAY):
        memcpy_P(current_face, face_OKAY[rand() % 4], sizeof(current_face));
        break;
      case(BAD):
        memcpy_P(current_face, face_BAD[rand() % 4], sizeof(current_face));
        break;
      case(TOXIC):
        memcpy_P(current_face, face_TOXIC[rand() % 2], sizeof(current_face));
        break;
      case(ERROR):
        memcpy_P(current_face, error, sizeof(current_face));
        break;
    }
    last_face_update = millis();

    // Update the LED matrix
    for(int y = 0; y < 8; y++) {
      for(int x = 0; x < 8; x++) {
        char code = current_face[7-x][y];
        uint32_t color = strip.Color(0, 0, 0); // Default to off
        for (const auto& entry : colors) {
          if (entry.code == code) {
            color = entry.color;
            break;
          }
        }
        strip.setPixelColor(y * 8 + x, color);
      }
    }
  }
  strip.setBrightness(brightness);
  strip.show();
  frame++;
}

