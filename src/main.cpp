void setup() {
  pinMode(MHZ19C_PWM_PIN, INPUT);
  pinMode(BUTTON_PIN, INPUT);
  SPI.begin(7, -1, 5, -1); // SCK=7, MISO=N/A, MOSI=5, SS=N/A
  Serial.begin(115200);
  Serial.println("CO2 Monitor Starting...");
  strip.begin();
  strip.clear();           // Turn all pixels off
  strip.show(); 
  display.init(115200);
  display.setFullWindow();
  display.firstPage();
  display.fillScreen(GxEPD_WHITE);
  if(firstboot) {
    display.setRotation(1);
    display.drawBitmap(0, 0, fire_bitmap, 200, 200, GxEPD_BLACK);
    display.display();
    firstBootAnimation();
  } else {
    Serial.println("Woke from deep sleep, already preheated");
  }
  awake_duration = 15000;
  brightness = 70;
  if(esp_sleep_get_wakeup_cause() == ESP_SLEEP_WAKEUP_TIMER) {
    if(getStateForPPM(getCO2PPM()) == last_state) { // No change in state, dim and short awake
      brightness = 10;
      awake_duration = 3000;
    } else { // Change in state, normal brightness and duration
      brightness = 150;
      awake_duration = 5000;
    }    
  } else if(!firstboot) { // Button wakeup
    brightness = 120;
    awake_duration = 5000;
    bootAnimation();
    Serial.println("Last state was: " + String(last_state));
    displayState(last_state);
  }
  awake_until = millis() + awake_duration;
  firstboot = false;
}

void loop() {
  if(millis() < awake_until) {
    Serial.println("Brightness: " + String(brightness));
    Serial.println("Sleep Duration: " + String(face_duration));
    int ppm = getCO2PPM();
    state = getStateForPPM(ppm);
    displayState(state);
    updateEpaper(state, ppm, first_update);
    first_update = false;
    delay(150);
  } else {
    goToDeepSleep();
  }
}

void firstBootAnimation() {
  unsigned long preheat_complete = millis() + 70000; // 70 s preheat
  int shown_seconds = -1;
  display.setPartialWindow(PREHEAT_TIMER_X, PREHEAT_TIMER_Y, PREHEAT_TIMER_W, PREHEAT_TIMER_H);
  while(millis() < preheat_complete) {
    int seconds_left = (preheat_complete - millis() + 9999) / 10000 * 10; // Round up to 10 s steps
    if(seconds_left != shown_seconds) {
      drawPreheatTimer(seconds_left);
      shown_seconds = seconds_left;
    }
    displayState(PREHEAT);
    Serial.println("Preheating for another " + String((preheat_complete - millis()) / 1000) + " seconds...");
    delay(150);
  }
  display.setFullWindow(); // First reading after preheat does a full refresh
  Serial.println("Preheat complete.");
}

// Partial refresh of the top-left corner only. The boot bitmap is redrawn inside
// the window so the background matches; its set bits are drawn black, hence white text.
void drawPreheatTimer(int seconds) {
  do {
    display.fillRect(PREHEAT_TIMER_X, PREHEAT_TIMER_Y, PREHEAT_TIMER_W, PREHEAT_TIMER_H, GxEPD_WHITE);
    display.drawBitmap(0, 0, fire_bitmap, 200, 200, GxEPD_BLACK);
    display.setTextColor(GxEPD_WHITE);
    display.setFont(&FreeSansBold12pt7b);
    display.setCursor(PREHEAT_TIMER_X + 3, PREHEAT_TIMER_Y + 20);
    display.print(String(seconds) + "s");
  } while(display.nextPage());
}

int getCO2PPM() {
  unsigned long awake_duration_left = awake_until - millis();
  float co2ppm = 0;
  unsigned long highTime = pulseIn(MHZ19C_PWM_PIN, HIGH, 5000000); // 5s timeout
  unsigned long lowTime = pulseIn(MHZ19C_PWM_PIN, LOW, 5000000);

  // pulseIn() returns microseconds; datasheet offsets are 2 ms and 4 ms
  if (highTime >= 2000 && lowTime >= 2000) {
      unsigned long period = highTime + lowTime;
      co2ppm = 2000.0 * (highTime - 2000) / (period - 4000);

      Serial.print("CO2 ppm: ");
      Serial.println(co2ppm);
  } else {
      Serial.println("Invalid reading. State: ERROR");
      return -1;
  }
  if(first_update) awake_until = millis() + awake_duration_left; // Restore awake duration
  return (int)co2ppm;
}

