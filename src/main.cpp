void updateEpaper(CURRENT_STATE state, int ppm, bool force_update) {
  if(millis() - last_epaper_update >= 60000 || state != last_state || force_update) { // Update every minute or on state change
    last_epaper_update = millis();
    last_state = state;
    do {
      display.fillScreen(GxEPD_WHITE);
      display.setTextColor(GxEPD_BLACK);
      display.setRotation(1);
      display.setFont(&FreeSansBold12pt7b);
      display.setCursor(35, 35);
      display.print("CO2 PPM: ");
      display.setFont(&FreeSansBold18pt7b);
      display.setCursor(60, 75);
      display.print(ppm);
      display.drawFastHLine(0, 90, 200, GxEPD_BLACK);
      display.setCursor(30, 125);
      display.setFont(&FreeSansBold12pt7b);
      display.print("Air Quality:");
      display.setCursor(45, 165);
      display.setFont(&FreeSansBold18pt7b);
      display.print(String(getNameOfState(state)));
      
    } while (display.nextPage());
  } else Serial.println("E-paper update not needed yet.");
}